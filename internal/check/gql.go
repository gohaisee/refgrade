// db driver import in resolver package
type Gql01 struct{ Base }

func NewGql01() *Gql01 {
	return &Gql01{Base: Base{meta: Meta{ID: "gql-01", Gates: gqlGates, Domain: "graphql", DefaultSeverity: SeverityFail}}}
}

func (c *Gql01) Run(ctx context.Context, mod ModuleView) ([]Finding, error) {
	_ = ctx
	if checkDisabled(mod, c.ID()) {
		return nil, nil
	}
	pool, err := poolFor(mod, astutil.DefaultFilter())
	if err != nil {
		return nil, err
	}
	var findings []Finding
	for _, f := range pool.Files {
		if !isResolverFilePath(f.RelPath) || astutil.IsTestFile(f.RelPath) || isGqlGeneratedFile(f.RelPath) {
			continue
		}
		for _, imp := range f.Imports {
			if _, ok := dbDriverImports[imp]; ok {
				findings = append(findings, finding(c.ID(), effectiveSeverity(mod, c.ID(), SeverityFail), f.RelPath, 1))
				break
			}
		}
	}
	return findings, nil
}

