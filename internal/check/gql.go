func isResolverFilePath(rel string) bool {
	rel = filepath.ToSlash(rel)
	return strings.Contains(rel, "/resolver/") || strings.Contains(rel, "/resolvers/")
}

func isGqlGeneratedFile(rel string) bool {
	base := filepath.Base(rel)
	return base == "generated.go" || base == "models_gen.go"
}

func isHandWrittenResolverFile(f *astutil.File) bool {
	return isHandWrittenResolverRel(f.RelPath)
}

func isHandWrittenResolverRel(rel string) bool {
	return isResolverFilePath(rel) && !astutil.IsTestFile(rel) && !isGqlGeneratedFile(rel)
}

func isEntityResolverFile(rel string) bool {
	base := filepath.Base(rel)
	return base == "entity.resolvers.go" || strings.Contains(base, "entity.resolver")
}

func loopBody(n ast.Node) *ast.BlockStmt {
	switch v := n.(type) {
	case *ast.ForStmt:
		return v.Body
	case *ast.RangeStmt:
		return v.Body
	default:
		return nil
	}
}

func isDbQueryCall(f *astutil.File, call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	name := sel.Sel.Name
	if _, ok := dbQueryMethods[name]; !ok {
		return false
	}
	if imp, resolved, ok := selectorImport(f, sel); ok {
		if !isSQLStorageImport(imp) {
			return false
		}
		_, ok = dbQueryMethods[resolved]
		return ok
	}
	if !looksLikeDBReceiver(sel.X) {
		return false
	}
	return fileHasSQLStorageImport(f) || isResolverFilePath(f.RelPath)
}

func fileHasBatchHint(f *astutil.File) bool {
	src := strings.ToLower(string(f.Src))
	for _, hint := range batchHints {
		if strings.Contains(src, strings.ToLower(hint)) {
			return true
		}
	}
	return false
}

func moduleHasGraphQLServer(mod ModuleView) bool {
	goMod := string(mod.GoModContent())
	return strings.Contains(goMod, "github.com/99designs/gqlgen") ||
		strings.Contains(goMod, "github.com/graph-gophers/graphql-go") ||
		strings.Contains(goMod, "github.com/graphql-go/graphql")
}

func moduleImportsGraphQLGo(mod ModuleView) bool {
	goMod := string(mod.GoModContent())
	return strings.Contains(goMod, "github.com/graph-gophers/graphql-go") ||
		strings.Contains(goMod, "github.com/graphql-go/graphql")
}

func moduleHasHint(pool *astutil.Pool, hints []string) bool {
	for _, f := range pool.Files {
		if astutil.IsTestFile(f.RelPath) {
			continue
		}
		src := string(f.Src)
		for _, hint := range hints {
			if strings.Contains(src, hint) {
				return true
			}
		}
	}
	return false
}

func firstGraphQLServerSetup(pool *astutil.Pool) (file string, line int, ok bool) {
	hints := []string{
		"github.com/99designs/gqlgen", "github.com/graph-gophers/graphql-go",
		"github.com/graphql-go/graphql", "handler.New", "graphql.Do", "relay.Handler",
	}
	for _, f := range pool.Files {
		if astutil.IsTestFile(f.RelPath) {
			continue
		}
		for _, hint := range hints {
			if strings.Contains(string(f.Src), hint) {
				return f.RelPath, 1, true
			}
		}
	}
	return "", 0, false
}

func firstGraphQLHandlerSetup(pool *astutil.Pool) (file string, line int, ok bool) {
	hints := []string{"graphql.Do", "relay.Handler", "graphql.Schema", "graphql.NewSchema"}
	for _, f := range pool.Files {
		if astutil.IsTestFile(f.RelPath) {
			continue
		}
		for _, hint := range hints {
			if strings.Contains(string(f.Src), hint) {
				return f.RelPath, 1, true
			}
		}
	}
	return "", 0, false
}

func fileHasIntrospection(f *astutil.File) bool { return f.ContainsAny(introspectionHints...) }

func introspectionLine(f *astutil.File) int {
	src := string(f.Src)
	for _, hint := range introspectionHints {
		if idx := strings.Index(src, hint); idx >= 0 {
			return strings.Count(src[:idx], "\n") + 1
		}
	}
	return 1
}

func fileHasPlayground(f *astutil.File) bool { return f.ContainsAny(playgroundHints...) }

func playgroundLine(f *astutil.File) int {
	src := string(f.Src)
	for _, hint := range playgroundHints {
		if idx := strings.Index(src, hint); idx >= 0 {
			return strings.Count(src[:idx], "\n") + 1
		}
	}
	return 1
}

func hasDevOrEnvGuard(src string) bool {
	if hasDevBuildTag(src) {
		return true
	}
	for _, g := range []string{
		"os.Getenv", "Getenv(", ".Env.", "cfg.", "config.",
		"IsDev", "IsProd", "IsProduction", "APP_ENV", "Environment",
	} {
		if strings.Contains(src, g) {
			return true
		}
	}
	return false
}

func isMapStringInterface(n ast.Node) bool {
	typ, ok := n.(*ast.MapType)
	if !ok {
		return false
	}
	key, ok := typ.Key.(*ast.Ident)
	if !ok || key.Name != "string" {
		return false
	}
	switch v := typ.Value.(type) {
	case *ast.InterfaceType:
		return true
	case *ast.Ident:
		return v.Name == "interface{}"
	case *ast.IndexExpr:
		if ident, ok := v.X.(*ast.Ident); ok && ident.Name == "interface" {
			return true
		}
	case *ast.IndexListExpr:
		if ident, ok := v.X.(*ast.Ident); ok && ident.Name == "interface" {
			return true
		}
	}
	return false
}

func funcHasAuthHint(fn *ast.FuncDecl) bool {
	if fn.Body == nil {
		return false
	}
	found := false
	ast.Inspect(fn.Body, func(n ast.Node) bool {
		switch v := n.(type) {
		case *ast.Ident:
			for _, hint := range authHints {
				if strings.Contains(v.Name, hint) {
					found = true
					return false
				}
			}
		case *ast.SelectorExpr:
			for _, hint := range authHints {
				if strings.Contains(v.Sel.Name, hint) {
					found = true
					return false
				}
			}
		}
		return true
	})
	return found
}

func fileHasGetGraphQLQuery(f *astutil.File) bool {
	src := string(f.Src)
	return strings.Contains(src, "Query.Get(\"query\")") ||
		strings.Contains(src, "Query.Get(\"Query\")") ||
		(strings.Contains(src, "URL.Query()") && strings.Contains(src, "query"))
}

func isGetQueryParamCall(f *astutil.File, call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Get" || len(call.Args) != 1 {
		return false
	}
	lit, ok := call.Args[0].(*ast.BasicLit)
	if !ok {
		return false
	}
	val := strings.Trim(lit.Value, `"`)
	if val != "query" && val != "Query" {
		return false
	}
	return isQueryGetter(sel)
}

func isQueryGetter(sel *ast.SelectorExpr) bool {
	inner, ok := sel.X.(*ast.SelectorExpr)
	if !ok || inner.Sel.Name != "Query" {
		return false
	}
	ident, ok := inner.X.(*ast.Ident)
	if !ok {
		return false
	}
	return ident.Name == "URL" || ident.Name == "r" || ident.Name == "req"
}
