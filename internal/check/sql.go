// edge traversal or Query inside loop when ent imported
type Ent01 struct{ Base }

func NewEnt01() *Ent01 {
	return &Ent01{Base: Base{meta: Meta{ID: "ent-01", Gates: []string{"ent"}, Domain: "sql", DefaultSeverity: SeverityWarn}}}
}

func (c *Ent01) Run(ctx context.Context, mod ModuleView) ([]Finding, error) {
	_ = ctx
	if checkDisabled(mod, c.ID()) {
		return nil, nil
	}
	pool, err := sqlInspect(mod)
	if err != nil {
		return nil, err
	}
	sev := effectiveSeverity(mod, c.ID(), SeverityWarn)
	var findings []Finding
	pool.Inspect(func(f *astutil.File, n ast.Node) bool {
		if !fileImportsEnt(f) {
			return true
		}
		var body ast.Node
		switch loop := n.(type) {
		case *ast.ForStmt:
			body = loop.Body
		case *ast.RangeStmt:
			body = loop.Body
		default:
			return true
		}
		ast.Inspect(body, func(n ast.Node) bool {
			sel, ok := n.(*ast.SelectorExpr)
			if !ok || !isEntTraversal(sel) {
				return true
			}
			findings = append(findings, finding(c.ID(), sev, f.RelPath, pool.Line(sel)))
			return true
		})
		return true
	})
	return findings, nil
}
