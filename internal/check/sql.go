type Sql01 struct{ Base }

func NewSql01() *Sql01 {
	return &Sql01{Base: Base{meta: Meta{ID: "sql-01", Gates: sqlGates(), Domain: "sql", DefaultSeverity: SeverityWarn}}}
}

func (c *Sql01) Run(ctx context.Context, mod ModuleView) ([]Finding, error) {
	_ = ctx
	if checkDisabled(mod, c.ID()) {
		return nil, nil
	}
	pool, err := sqlInspect(mod)
	if err != nil {
		return nil, err
	}
	sev := effectiveSeverity(mod, c.ID(), SeverityWarn)
	var findings []Finding
	pool.Inspect(func(f *astutil.File, n ast.Node) bool {
		switch loop := n.(type) {
		case *ast.ForStmt:
			inspectLoopBody(pool, f, loop.Body, c.ID(), sev, &findings)
		case *ast.RangeStmt:
			inspectLoopBody(pool, f, loop.Body, c.ID(), sev, &findings)
		}
		return true
	})
	return findings, nil
}

