var (
	sqlMethodNames = map[string]struct{}{
		"Query": {}, "QueryRow": {}, "Exec": {},
		"Get": {}, "Select": {}, "Queryx": {}, "QueryRowx": {},
		"Find": {}, "First": {}, "Take": {}, "Last": {},
		"Create": {}, "Save": {}, "Delete": {}, "Raw": {}, "Scan": {},
	}

	sqlPackageCalls = map[string]map[string]struct{}{
		"database/sql":                    {"Open": {}},
		"github.com/jackc/pgx/v5":         {"Connect": {}},
		"github.com/jackc/pgx/v5/pgxpool":   {"New": {}, "NewWithConfig": {}},
		"github.com/jmoiron/sqlx":         {"Connect": {}, "Open": {}},
	}

	sqlKeywordsRe   = regexp.MustCompile(`(?i)\b(SELECT|INSERT|UPDATE|DELETE|FROM|WHERE)\b`)
	limitRe         = regexp.MustCompile(`(?i)\bLIMIT\b`)
	selectStarRe    = regexp.MustCompile(`(?i)SELECT\s+\*`)
	offsetRe        = regexp.MustCompile(`(?i)\bOFFSET\b`)
	moneyFieldRe    = regexp.MustCompile(`(?i)(amount|price|balance|cost|fee|money|total|payment|currency|revenue|salary|wage)`)
	sqlcGeneratedRe = regexp.MustCompile(`(?i)code generated by sqlc`)
)

func sqlGates() []string {
	return []string{"pgx", "gorm", "sqlx", "sqlc", "ent", "database/sql"}
}

func sqlInspect(mod ModuleView) (*astutil.Pool, error) {
	return poolFor(mod, astutil.Filter{SkipTestFiles: true})
}

func inspectLoopBody(pool *astutil.Pool, f *astutil.File, body ast.Node, id, sev string, findings *[]Finding) {
	if body == nil {
		return
	}
	ast.Inspect(body, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		if isSQLDataCall(f, call) {
			*findings = append(*findings, finding(id, sev, f.RelPath, pool.Line(call)))
		}
		return true
	})
}

func isSQLDataCall(f *astutil.File, call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	if _, ok := sqlMethodNames[sel.Sel.Name]; ok {
		return true
	}
	imp, name, ok := f.Selector(sel)
	if !ok {
		return false
	}
	methods, ok := sqlPackageCalls[imp]
	if !ok {
		return false
	}
	_, ok = methods[name]
	return ok
}

func isPoolOpenCall(f *astutil.File, call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	imp, name, ok := selectorImport(f, sel)
	if !ok {
		return false
	}
	methods, ok := sqlPackageCalls[imp]
	if !ok {
		return false
	}
	_, ok = methods[name]
	return ok
}

func selectorImport(f *astutil.File, sel *ast.SelectorExpr) (importPath, name string, ok bool) {
	if imp, name, ok := f.Selector(sel); ok {
		return imp, name, true
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", sel.Sel.Name, false
	}
	if imp, ok := importPathForIdent(f, ident.Name); ok {
		return imp, sel.Sel.Name, true
	}
	return "", sel.Sel.Name, false
}

func importPathForIdent(f *astutil.File, name string) (string, bool) {
	if p := f.ImportPathOf(name); p != "" {
		return p, true
	}
	for local, path := range f.Imports {
		if local == name {
			return path, true
		}
	}
	for _, path := range f.Imports {
		if name == "pgx" && strings.Contains(path, "jackc/pgx/v5") {
			return path, true
		}
	}
	return "", false
}

func isFmtSprintfSQL(call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Sprintf" {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok || ident.Name != "fmt" {
		return false
	}
	if len(call.Args) < 2 {
		return false
	}
	lit, ok := call.Args[0].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return false
	}
	return sqlKeywordsRe.MatchString(unquoteBasicLit(lit))
}

func unquoteBasicLit(lit *ast.BasicLit) string {
	s, err := strconv.Unquote(lit.Value)
	if err != nil {
		return strings.Trim(lit.Value, `"`)
	}
	return s
}

func isSQLString(s string) bool {
	return sqlKeywordsRe.MatchString(s)
}

func hasLimitInSQL(s string) bool {
	return limitRe.MatchString(s)
}

func hasSelectStar(s string) bool {
	return selectStarRe.MatchString(s)
}

func hasOffsetInSQL(s string) bool {
	return offsetRe.MatchString(s)
}

func isListFuncName(name string) bool {
	return strings.HasPrefix(name, "List") || strings.HasPrefix(name, "FindAll")
}

func funcBodySQLStrings(body *ast.BlockStmt) []string {
	if body == nil {
		return nil
	}
	var out []string
	ast.Inspect(body, func(n ast.Node) bool {
		lit, ok := n.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		s := unquoteBasicLit(lit)
		if isSQLString(s) {
			out = append(out, s)
		}
		return true
	})
	return out
}

func exprHasStringConcat(expr ast.Expr) bool {
	switch e := expr.(type) {
	case *ast.BinaryExpr:
		if e.Op != token.ADD {
			return false
		}
		_, leftStr := e.X.(*ast.BasicLit)
		_, rightStr := e.Y.(*ast.BasicLit)
		if leftStr || rightStr {
			return true
		}
		return exprHasStringConcat(e.X) || exprHasStringConcat(e.Y)
	default:
		return false
	}
}

func isMoneyFieldName(name string) bool {
	return moneyFieldRe.MatchString(name)
}

func isFloat64Type(expr ast.Expr) bool {
	ident, ok := expr.(*ast.Ident)
	return ok && ident.Name == "float64"
}

func isGormDBType(expr ast.Expr) bool {
	star, ok := expr.(*ast.StarExpr)
	if !ok {
		return false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	return ok && ident.Name == "gorm" && sel.Sel.Name == "DB"
}

func isRemoteSSLModeDisable(s string) bool {
	lower := strings.ToLower(s)
	if !strings.Contains(lower, "sslmode=disable") {
		return false
	}
	if strings.Contains(lower, "localhost") || strings.Contains(lower, "127.0.0.1") {
		return false
	}
	return strings.Contains(s, "@") || strings.Contains(lower, "host=")
}

func isErrErrorStringCompare(n ast.Node) bool {
	switch node := n.(type) {
	case *ast.BinaryExpr:
		if node.Op != token.EQL && node.Op != token.NEQ {
			return false
		}
		return isErrErrorExpr(node.X) || isErrErrorExpr(node.Y)
	case *ast.CallExpr:
		sel, ok := node.Fun.(*ast.SelectorExpr)
		if !ok {
			return false
		}
		ident, ok := sel.X.(*ast.Ident)
		if !ok || ident.Name != "strings" {
			return false
		}
		switch sel.Sel.Name {
		case "Contains", "HasPrefix", "HasSuffix", "EqualFold":
			for _, arg := range node.Args {
				if isErrErrorExpr(arg) {
					return true
				}
			}
		}
	}
	return false
}

func isErrErrorExpr(expr ast.Expr) bool {
	call, ok := expr.(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Error" {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	return ok && ident.Name == "err"
}

func countPreloadChain(call *ast.CallExpr) int {
	count := 0
	cur := call
	for {
		sel, ok := cur.Fun.(*ast.SelectorExpr)
		if !ok {
			break
		}
		if sel.Sel.Name == "Preload" {
			count++
		}
		inner, ok := sel.X.(*ast.CallExpr)
		if !ok {
			break
		}
		cur = inner
	}
	return count
}

func callEndsWithFind(call *ast.CallExpr) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "Find"
}

func isGormPreloadFindChain(call *ast.CallExpr) bool {
	if !callEndsWithFind(call) {
		return false
	}
	return countPreloadChain(call) >= 2
}

func isEntTraversal(sel *ast.SelectorExpr) bool {
	return sel.Sel.Name == "Edges"
}

func fileImportsGorm(f *astutil.File) bool {
	return fileImportsPath(f, "gorm.io/gorm")
}

func fileImportsSqlx(f *astutil.File) bool {
	return fileImportsPath(f, "github.com/jmoiron/sqlx")
}

func fileImportsEnt(f *astutil.File) bool {
	if fileImportsPath(f, "entgo.io/ent") {
		return true
	}
	for _, spec := range f.AST.Imports {
		path := strings.Trim(spec.Path.Value, `"`)
		if path == "entgo.io/ent" || strings.HasPrefix(path, "entgo.io/ent/") {
			return true
		}
	}
	return false
}

func isSqlxNoCtxCall(f *astutil.File, call *ast.CallExpr) bool {
	if !fileImportsSqlx(f) {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	switch sel.Sel.Name {
	case "Get", "Select":
		return true
	default:
		return false
	}
}

